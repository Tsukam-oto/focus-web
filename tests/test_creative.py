from pathlib import Path
from playwright.sync_api import sync_playwright
import json,re
root=Path(__file__).resolve().parents[1]/'public'
html=(root/'index.html').read_text()
html=re.sub(r'<script src="\./[^\"]+\.js" defer></script>','',html)
html=html.replace('<link rel="stylesheet" href="./focus-v5.css" />','<style>'+(root/'focus-v5.css').read_text()+'</style>')
checks=[]
def ok(cond,desc):
    assert cond,desc
    checks.append(desc)
with sync_playwright() as p:
 b=p.chromium.launch(headless=True,args=['--no-sandbox'])
 page=b.new_page(viewport={'width':390,'height':844},accept_downloads=True);page.set_default_timeout(4000)
 errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
 page.set_content(html)
 page.evaluate('''()=>{Object.defineProperty(window,'localStorage',{configurable:true,value:{storage:{},getItem(k){return this.storage[k]??null},setItem(k,v){this.storage[k]=v},removeItem(k){delete this.storage[k]}}});Object.defineProperty(window,'indexedDB',{configurable:true,value:null});}''')
 for n in ['install.js','app.js','studio.js','privacy-v5.js','creative.js']:
  page.add_script_tag(content=(root/n).read_text())
 page.get_by_role('button',name='制作',exact=True).click()
 ok(page.locator('#panel-creative').is_visible(),'制作ワークスペース表示')
 ok('録音一覧の読み込みに失敗' in page.locator('#audioStatus').inner_text(),'録音が使えない環境では説明表示')
 ok(not page.locator('[data-tab="reward"]').is_visible(),'通常モードの画像交換は非表示')
 page.locator('#createIdea').click()
 ok(page.locator('#creativeTitle').input_value()=='アイデアメモ','アイデアテンプレ')
 ok('次にやること' in page.locator('#creativeBody').input_value(),'テンプレ本文')
 page.locator('#creativeTitle').fill('新曲のメモ')
 page.locator('#creativeBody').fill('# 新曲\nコード進行 C G Am F')
 page.wait_for_timeout(700)
 saved=json.loads(page.evaluate("localStorage.getItem('focus-creative-workspace-v1')"))
 ok(saved['docs'][0]['title']=='新曲のメモ' and 'C G' in saved['docs'][0]['body'],'入力の自動保存')
 page.locator('#createCode').click()
 page.locator('#creativeTitle').fill('music.js')
 page.locator('#creativeBody').fill('const tempo = 120;\n')
 page.wait_for_timeout(700)
 data=page.evaluate('window.FocusCreative.exportPackage()')
 ok(len(data['docs'])==2,'2ファイルをバックアップ')
 page.locator('#creativeSearch').fill('進行')
 ok(page.locator('#creativeDocuments .creative-doc').count()==1,'本文検索')
 page.locator('#creativeSearch').fill('')
 page.locator('#creativeDocuments .creative-doc').nth(1).click()
 ok(page.locator('#creativeTitle').input_value()=='新曲のメモ','ファイル切替')
 with page.expect_download() as d:
  page.locator('#creativeDownload').click()
 ok(d.value.suggested_filename=='新曲のメモ.md','Markdownを書き出し')
 # exported backup can restore without replacing focus session
 page.on('dialog',lambda d:d.accept())
 page.locator('#creativeDelete').click()
 ok(len(page.evaluate('window.FocusCreative.exportPackage().docs'))==1,'ファイル削除')
 page.evaluate('(d)=>window.FocusCreative.restorePackage(d)',data)
 ok(len(page.evaluate('window.FocusCreative.exportPackage().docs'))==2,'制作データ復元')
 page.get_by_role('button',name='集中',exact=True).click()
 page.locator('#focusCategory').select_option('創作')
 ok(page.locator('#creativeJump').is_visible(),'創作ジャンルで制作導線を表示')
 page.locator('#startBtn').click()
 page.locator('#creativeJump').click()
 page.wait_for_timeout(1100)
 ok(page.locator('#panel-creative').is_visible() and '集中中' in page.locator('#creativeTimerStatus').inner_text(),'制作画面でも集中タイマー継続')
 page.locator('#creativeBackToFocus').click()
 ok(page.locator('#panel-focus').is_visible(),'制作からタイマーへ復帰')
 ok(not errors,'JS実行エラーなし: '+repr(errors))
 page.get_by_role('button',name='制作',exact=True).click()
 page.locator('#creativeSearch').fill('')
 page.locator('#creativeDocuments .creative-doc').nth(0).click()
 page.screenshot(path=str(root.parent/'preview-creative-mobile.png'),full_page=True)
 b.close()
print('PASS',len(checks),'\n'+'\n'.join(checks))
